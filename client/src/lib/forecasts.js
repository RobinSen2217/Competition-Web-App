// Machine-learning forecasts (the notebook's Ridge / neural network / gradient
// boosting models, run by the server's forecasting module in server/ml) on the
// team notebook's Google Earth Engine data: Landsat NDVI and ERA5-Land weather
// over a small box around each city, extracted by the server
// (`npm run gee:extract`). Not the site's own MODIS/NASA series.
//
// Where the numbers come from:
// - API in use (DATA_SOURCE 'api'): GET /api/v1/areas/:id/forecasts. The server
//   runs the models live, or answers from its own saved snapshot when it cannot
//   (data.source and meta.fallback say which). A live run can take several
//   seconds, hence the long timeout.
// - Otherwise, or when that request fails: the saved snapshot of the same
//   response, public/data/forecasts/<id>.<target>.json, generated by the server
//   from the same module (24 months, every model; cut down here to the
//   request). The site then still has a forecast on static hosting.
//
// Both return the module's response shape, so components never care which:
//   { version, area, target, interval, issued: 'YYYY-MM', forecastTimes: [...],
//     models: { ridge|nn|gbm: { label, forecast: [...],
//       hindcast: { times, observed, predicted, r2, rmse },
//       metrics: { train|test: { r2, rmse, from, to, n } },
//       importance: [{ feature, label, value }] } },
//     history: { times: ['YYYY-MM', ...], observed: [NDVI | null, ...] },  the
//       model's own observed series (Landsat), the one to plot it against
//     features: [{ key, label, unit }], assumptions: [...], modelVersion, dataUntil,
//     provenance: { pipeline, datasets: [Earth Engine ids], areaKm, generated } }
//
// A city whose Earth Engine data has not been extracted yet has no forecast
// anywhere (the API answers 503 with details.reason 'no_gee_data' and there is
// no saved snapshot). loadForecast then rejects with code NOT_EXTRACTED, a
// normal state the panel shows calmly, unlike a real failure.
import { asset } from './asset'
import { fetchForecast } from './api'
import { DATA_SOURCE } from './store'

// A live run trains three models, so allow far longer than the 4 s startup wait.
const API_TIMEOUT_MS = 20000

const DEFAULTS = { target: 'ndvi', horizon: 12, models: ['ridge', 'nn', 'gbm'] }

export const NOT_EXTRACTED = 'not_extracted'

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)

// Minimal shape check: enough that the panel can draw something, for the
// parameter that was asked for. A response missing these (a half-deployed
// server) counts as a failure, so the API path falls back to the snapshot
// instead of crashing the panel.
function valid(d, opts) {
  return isObj(d) && d.target === opts.target && typeof d.issued === 'string' && Array.isArray(d.forecastTimes) && d.forecastTimes.length > 0 && isObj(d.models) && Object.keys(d.models).length > 0
}

// Forecasts made before the Earth Engine pipeline (from the site's own data)
// have no provenance; they are not this model's output, so treat them as absent.
const fromGee = (d) => isObj(d) && isObj(d.provenance)

// Error for "no forecast exists for this city yet" (see the header comment)
function notExtracted(areaId) {
  const e = new Error(`no Earth Engine data extracted for ${areaId} yet`)
  e.code = NOT_EXTRACTED
  return e
}

// What the panel needs besides the forecast: where it came from. `source` is
// the server's data.source ('live' | 'snapshot'), never how it reached us;
// generated (ISO time it was computed) and fallback (why a saved forecast was
// served) come from meta when present.
const answer = (d, meta) => ({
  data: d,
  source: d.source === 'live' ? 'live' : 'snapshot',
  generated: typeof meta?.generated === 'string' ? meta.generated : null,
  fallback: typeof meta?.fallback === 'string' ? meta.fallback : null,
})

async function fromApi(areaId, opts) {
  const ctrl = new AbortController()
  const timer = setTimeout(() => ctrl.abort(), API_TIMEOUT_MS)
  try {
    const { data, meta } = await fetchForecast(areaId, opts, ctrl.signal)
    if (!valid(data, opts) || !fromGee(data)) throw new Error('response has no forecast')
    return answer(data, meta)
  } finally {
    clearTimeout(timer)
  }
}

// `missing` (no file, or only a pre-Earth Engine one) is told apart from an
// unreadable file, because only the first is the normal "not extracted yet".
async function fromSnapshot(areaId, opts) {
  const missing = () => Object.assign(new Error(`no saved forecast for ${areaId}`), { missing: true })
  const res = await fetch(asset(`/data/forecasts/${areaId}.${opts.target}.json`))
  if (!res.ok) throw missing()
  // Static hosts answer unknown paths with index.html, so a parse error means "missing" too
  const body = await res.json().catch(() => null)
  if (body === null) throw missing()
  // Accept the bare module response or one wrapped in the API envelope
  const wrapped = isObj(body) && 'data' in body && !('models' in body)
  const d = wrapped ? body.data : body
  if (isObj(d) && !fromGee(d)) throw missing()
  if (!valid(d, opts)) throw new Error(`saved forecast for ${areaId} is unreadable`)
  // Always a saved forecast, whatever the file says
  return answer({ ...d, source: 'snapshot' }, wrapped ? body.meta : null)
}

// The snapshot holds every model for the longest horizon; keep only the
// requested models and months so both sources answer the same question (the
// API's answer already matches, so this changes nothing there).
function fit(r, { models, horizon }) {
  const d = r.data
  const keep = Object.fromEntries(Object.entries(d.models).filter(([k]) => models.includes(k)).map(([k, m]) => [k, { ...m, forecast: (m.forecast || []).slice(0, horizon) }]))
  if (!Object.keys(keep).length) return r
  return { ...r, data: { ...d, forecastTimes: d.forecastTimes.slice(0, horizon), models: keep } }
}

// Cached per area + request, so switching cities back and forth (or the model
// selector re-rendering) never re-runs the models. A failed load is dropped
// from the cache so "Retry" really tries again.
const cache = new Map()

// loadForecast('jaipur') -> Promise<{ data, source: 'live' | 'snapshot',
// generated: ISO string | null, fallback: string | null }>; throws when neither
// source has a forecast for the area: with code NOT_EXTRACTED when there is
// simply none yet (the API said no_gee_data, or there is no API and no saved
// forecast), otherwise a real failure.
export function loadForecast(areaId, options = {}) {
  const opts = { ...DEFAULTS, ...options }
  const key = [areaId, opts.target, opts.horizon, opts.models.join(',')].join('|')
  if (!cache.has(key)) {
    const p = (async () => {
      // The API's reason, kept to decide what a missing snapshot means
      let apiError = null
      if (DATA_SOURCE === 'api') {
        try {
          return fit(await fromApi(areaId, opts), opts)
        } catch (e) {
          apiError = e
          if (e.details?.reason !== 'no_gee_data') console.warn(`[forecast] API unavailable for ${areaId}, using the saved snapshot: ${e.message}`)
        }
      }
      try {
        return fit(await fromSnapshot(areaId, opts), opts)
      } catch (e) {
        if (!e.missing) throw e
        // No saved forecast: "not yet" unless the API had the data and failed
        // (or could not be reached, so we cannot tell), which is a real failure.
        const apiSaidNoData = apiError?.details?.reason === 'no_gee_data'
        if (DATA_SOURCE !== 'api' || apiSaidNoData) throw notExtracted(areaId)
        throw apiError || e
      }
    })().catch((e) => {
      cache.delete(key)
      throw e
    })
    cache.set(key, p)
  }
  return cache.get(key)
}
